#!/usr/bin/env node
/**
 * Generate TypeScript API client from OpenAPI schema
 *
 * This script fetches the OpenAPI schema from the running Django backend
 * and generates TypeScript types and a typed fetch client.
 *
 * Usage:
 *   node bin/generate-api-client.mjs [options]
 *
 * Options:
 *   --schema-url URL    URL to fetch OpenAPI schema from (default: http://localhost:8000/api/schema/)
 *   --output PATH       Output path for generated types (default: src/lib/api-types.ts)
 *   --help              Show this help message
 */
import fs from 'fs/promises'
import openapiTS from 'openapi-typescript'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const rootDir = path.resolve(__dirname, '..')

// Parse command line arguments
const args = process.argv.slice(2)
const getArg = (name, defaultValue) => {
    const index = args.indexOf(name)
    return index !== -1 && args[index + 1] ? args[index + 1] : defaultValue
}

if (args.includes('--help') || args.includes('-h')) {
    console.log(`
Generate TypeScript API client from OpenAPI schema

Usage:
  node bin/generate-api-client.mjs [options]

Options:
  --schema-url URL    URL to fetch OpenAPI schema from (default: http://localhost:8000/api/schema/)
  --output PATH       Output path for generated types (default: src/lib/api-types.ts)
  --help, -h          Show this help message

Examples:
  # Generate from local backend
  node bin/generate-api-client.mjs

  # Generate from production
  node bin/generate-api-client.mjs --schema-url https://app.posthog.com/api/schema/

  # Custom output path
  node bin/generate-api-client.mjs --output src/types/api.ts
`)
    process.exit(0)
}

const SCHEMA_URL = getArg('--schema-url', process.env.OPENAPI_SCHEMA_URL || 'http://localhost:8000/api/schema/')
const OUTPUT_PATH = getArg('--output', path.join(rootDir, 'src/lib/api-types.ts'))

async function checkBackendAvailability() {
    try {
        const response = await fetch(SCHEMA_URL, { method: 'HEAD' })
        return response.ok
    } catch (error) {
        return false
    }
}

async function generateApiTypes() {
    console.log('🔍 Checking backend availability...')

    const isBackendAvailable = await checkBackendAvailability()
    if (!isBackendAvailable) {
        console.error(`❌ Backend is not available at ${SCHEMA_URL}`)
        console.error('   Please ensure the Django backend is running.')
        console.error('   You can start it with: ./bin/start')
        console.error('   Or set OPENAPI_SCHEMA_URL to a different endpoint.')
        process.exit(1)
    }

    console.log('✅ Backend is available')
    console.log(`📥 Fetching OpenAPI schema from ${SCHEMA_URL}...`)

    try {
        // Generate TypeScript types from OpenAPI schema
        const output = await openapiTS(SCHEMA_URL, {
            commentHeader: `
/**
 * Auto-generated TypeScript types from PostHog OpenAPI schema
 *
 * DO NOT EDIT THIS FILE MANUALLY
 *
 * Generated on: ${new Date().toISOString()}
 * Schema URL: ${SCHEMA_URL}
 *
 * To regenerate, run:
 *   pnpm api:generate
 *
 * Or manually:
 *   node bin/generate-api-client.mjs
 */
`,
            inject: '/* eslint-disable */',
        })

        // Ensure output directory exists
        const outputDir = path.dirname(OUTPUT_PATH)
        await fs.mkdir(outputDir, { recursive: true })

        // Write the generated types
        await fs.writeFile(OUTPUT_PATH, output)

        console.log(`✅ Generated API types at ${path.relative(rootDir, OUTPUT_PATH)}`)

        // Get file size for reporting
        const stats = await fs.stat(OUTPUT_PATH)
        const sizeKB = (stats.size / 1024).toFixed(2)
        console.log(`   File size: ${sizeKB} KB`)

        // Count the number of endpoints
        const endpointMatches = output.match(/paths: \{/g)
        if (endpointMatches) {
            console.log(`   Endpoints: ${endpointMatches.length}`)
        }
    } catch (error) {
        console.error('❌ Failed to generate API types:', error.message)
        if (error.cause) {
            console.error('   Cause:', error.cause)
        }
        process.exit(1)
    }
}

// Run the generator
generateApiTypes().catch((error) => {
    console.error('❌ Unexpected error:', error)
    process.exit(1)
})
